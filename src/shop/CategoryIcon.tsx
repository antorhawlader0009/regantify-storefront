/** Words in a category's slug or name, and the icon they get (first match wins). Super Admin's category list is free to change, so it is matched by words. */
const RULES: Array<[RegExp, LucideIcon]> = [
  [/phone|mobile|tablet/, Smartphone],
  [/laptop|computer|pc\b/, Laptop],
  [/tv|television/, Tv],
  [/head ?phone|earbud|audio|speaker/, Headphones],
  [/camera/, Camera],
  [/watch/, Watch],
  [/electr|gadget|charger|cable|appliance/, Plug],
  [/shoe|footwear|sandal|sneaker/, Footprints],
  [/jewel|ornament|gold|silver/, Gem],
  [/glass|sunglass|eyewear/, Glasses],
  [/bag|wallet|luggage/, ShoppingBag],
  [/baby|kid|child|toy/, Baby],
  [/game|gaming/, Gamepad2],
  [/beauty|cosmetic|makeup|skin|perfume|fragrance/, Sparkles],
  [/health|medic|pharma/, Pill],
  [/fitness|sport|gym/, Dumbbell],
  [/bike|cycle/, Bike],
  [/car|motor|auto/, Car],
  [/pet|animal/, PawPrint],
  [/book|station|stationery/, BookOpen],
  [/grocery|food|fruit|vegetable/, Apple],
  [/tea|coffee|drink|beverage/, Coffee],
  [/kitchen|cook|dining/, UtensilsCrossed],
  [/furniture|sofa|decor/, Sofa],
  [/home|house|living/, Home],
  [/garden|plant/, Leaf],
  [/flower/, Flower2],
  [/art|craft|paint/, Palette],
  [/tool|hardware|repair/, Wrench],
  [/gift/, Gift],
  [/care|wellness/, HeartPulse],
  [/fashion|cloth|wear|dress|shirt|saree|panjabi|kurti|three ?piece|apparel/, Shirt],
];

/** The icon for one of the Shop's categories (an outline icon from the same set as the dashboard; never an emoji). */
export function CategoryIcon({ slug, name, size = 26 }: { slug: string; name: string; size?: number }) {
  const text = `${slug} ${name}`.toLowerCase().replace(/-/g, ' ');
  const Icon = RULES.find(([re]) => re.test(text))?.[1] ?? Tag;
  return <Icon size={size} strokeWidth={1.8} aria-hidden />;
}
